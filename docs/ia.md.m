영화 미믹킹 훈련 서비스 IA
/ (Root)
│
├── / (Home - 영화 선택 페이지)
│   ├── 영화 목록 표시 (카드 형태)
│   │   ├── 영화 썸네일
│   │   ├── 영화 제목
│   │   └── 간단한 설명
│   └── 영화 선택 → /training/[movieId]로 이동
│
└── /training/[movieId] (훈련 페이지)
    ├── 사이드바 (토글 가능)
    │   ├── 토글 버튼
    │   ├── 문장(구간) 목록
    │   ├── 현재 선택된 문장 하이라이트
    │   └── 문장 클릭 → 해당 구간으로 이동
    │
    ├── 중앙 영역
    │   ├── 비디오 플레이어 (HTML5)
    │   │   ├── 클릭 시 재생/일시정지 토글
    │   │   ├── 일시정지 시: dimmed + "PAUSE" 표시
    │   │   ├── 기본 컨트롤 (시크바, 볼륨, 재생속도)
    │   │   └── 현재 문장 텍스트 (하단, 작게, 토글 가능)
    │   │
    │   └── 하단바
    │       ├── [←] 이전 문장 버튼
    │       ├── 8개 재생 버튼 (가로 일렬)
    │       │   ├── 버튼 1: 재생 (>)
    │       │   ├── 버튼 2: 재생 (>)
    │       │   ├── 버튼 3: 재생 (>)
    │       │   ├── 버튼 4: 무음재생 (m)
    │       │   ├── 버튼 5: 재생 (>)
    │       │   ├── 버튼 6: 무음재생 (m)
    │       │   ├── 버튼 7: 재생 (>)
    │       │   └── 버튼 8: 무음재생 (m)
    │       └── [→] 다음 문장 버튼
    │
    └── 키보드 단축키
        ├── Space: 재생/일시정지
        ├── ← / →: 이전/다음 문장
        └── >, m: 각 재생 버튼 실행

페이지별 상세 기능
1. / (영화 선택 페이지)

목적: 사용자가 훈련할 영화 선택
주요 요소:

영화 카드 그리드
각 카드: 썸네일 + 제목 + 설명


인터랙션: 카드 클릭 → 훈련 페이지 이동

2. /training/[movieId] (훈련 페이지)

목적: 영화 장면을 보며 미믹킹 훈련
주요 요소:

토글 가능한 사이드바 (문장 목록)
중앙 비디오 플레이어
8개 재생 버튼 하단바
이전/다음 네비게이션


인터랙션:

문장 선택 → 비디오 구간 이동
재생 버튼 → 현재 구간 재생/무음재생
키보드 단축키 지원